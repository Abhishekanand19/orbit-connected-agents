import {test,expect} from '@playwright/test';

test('review exact payload, approve and verify one task, reject another, survive reload',async({page,request},testInfo)=>{
 await page.goto('/');
 const panel=page.getByRole('region',{name:'Action approvals'});
 await expect(panel).toBeVisible();
 const approve=panel.locator('.approval-card').filter({hasText:'approve-task'});
 const reject=panel.locator('.approval-card').filter({hasText:'reject-task'});
 await expect(approve).toContainText('Prepare the launch notes');
 await expect(approve.locator('pre')).toContainText('"status": "DONE"');
 let before=await request.get('http://127.0.0.1:8002/api/nodes/approve-task');
 expect((await before.json()).properties.status).toBe('OPEN');
 await approve.getByRole('button',{name:'Why?',exact:true}).click();
 const why=page.getByRole('dialog',{name:'Why did Orbit do this?'});
 await expect(why).toBeVisible();await expect(why).toContainText('WAITING');
 await expect(why).toContainText('Mark Prepare the launch notes complete after your review.');
 await expect(why).not.toContainText('The approved action was completed');
 await page.screenshot({path:testInfo.outputPath('why-waiting.png'),fullPage:true});
 await why.getByRole('button',{name:'Close explanation'}).click();
 await approve.getByRole('button',{name:'Approve exact action'}).click();
 await expect(approve.locator('summary')).toContainText('VERIFIED');
 await reject.getByRole('button',{name:'Reject',exact:true}).click();
 await expect(reject.locator('summary')).toContainText('REJECTED');
 expect((await (await request.get('http://127.0.0.1:8002/api/nodes/approve-task')).json()).properties.status).toBe('DONE');
 expect((await (await request.get('http://127.0.0.1:8002/api/nodes/reject-task')).json()).properties.status).toBe('OPEN');
 await approve.getByRole('button',{name:'Why?',exact:true}).click();
 await expect(why).toContainText('The approved action was completed and matched a fresh readback.');
 await why.getByText('Inspect technical evidence').click();
 await expect(why.locator('pre')).toContainText('mcp-memory');
 await why.getByRole('button',{name:'Close explanation'}).click();
 await page.reload();await expect(panel).toBeVisible();await expect(approve.locator('summary')).toContainText('VERIFIED');
 for(const mode of ['Graph','Simple']){
  await page.getByRole('button',{name:'Open '+mode+' View',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Graph exploration workspace'})).toBeVisible();
  await expect(page.getByTestId('graph-canvas')).toBeVisible();
  await page.getByRole('button',{name:'Close graph workspace'}).click();
 }
 const decisionPanel=page.getByRole('region',{name:'Decision receipts'});
 await decisionPanel.getByRole('button',{name:'Why?',exact:true}).click();
 await expect(why).toContainText('The planning appointment changed');
 await expect(why).toContainText('Connected transport depends on Planning appointment');
 await page.screenshot({path:testInfo.outputPath('why-path.png'),fullPage:true});
 await why.getByRole('button',{name:'Close explanation'}).click();
 await expect(page.getByRole('log')).toContainText('Please prepare these test task changes for review.');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Close settings',exact:true}).click();
 await expect(panel).toBeVisible();
 await page.screenshot({path:testInfo.outputPath('approval-mobile.png'),fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
});
