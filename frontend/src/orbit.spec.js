import {test, expect} from '@playwright/test';
test('bot creation, settings, conversations and reload', async ({page}) => {
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5173');
 await expect(page.locator('.bot-item')).toHaveCount(5);
 await expect(page.locator('.bot-item svg path').first()).toBeVisible();
 await page.getByRole('button',{name:'Create new bot',exact:true}).click();
 await page.getByLabel('Bot name',{exact:true}).fill('Writing Companion');
 await page.getByLabel('Purpose',{exact:true}).last().fill('Help shape a story.');
 await page.getByRole('button',{name:'Pebble avatar'}).last().click();
 await page.getByRole('button',{name:'Lilac',exact:true}).last().click();
 await page.getByRole('button',{name:'Create bot',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Writing Companion',exact:true})).toBeVisible();
 await expect(page.locator('.bot-item')).toHaveCount(6);
 await page.getByLabel('Message',{exact:true}).fill('A first thought');
 await page.getByLabel('Message',{exact:true}).press('Shift+Enter');
 await page.getByLabel('Message',{exact:true}).press('End');
 await page.getByLabel('Message',{exact:true}).press('Enter');
 await expect(page.locator('.message-bubble')).toHaveText('A first thought');
 await page.getByLabel('Name',{exact:true}).fill('Story Companion');
 await page.getByLabel('Instructions / personality').fill('Be concise and curious.');
 await page.getByRole('button',{name:'Sage avatar'}).click();
 await page.getByRole('switch',{name:'Notifications'}).click();
 await page.getByRole('button',{name:'Save settings'}).click();
 await expect(page.getByRole('button',{name:'Settings saved'})).toBeVisible();
 await page.getByRole('button',{name:/Schedule Planner Make room/}).click();
 await expect(page.locator('.message-bubble')).toHaveCount(0);
 await page.getByLabel('Message',{exact:true}).fill('Plan tomorrow');await page.getByLabel('Message',{exact:true}).press('Enter');
 await page.getByRole('button',{name:/Story Companion Help shape/}).click();
 await expect(page.locator('.message-bubble')).toHaveText('A first thought');
 await page.reload();
 await expect(page.getByRole('heading',{name:'Story Companion',exact:true})).toBeVisible();
 await expect(page.locator('.message-bubble')).toHaveText('A first thought');
 await expect(page.getByLabel('Instructions / personality')).toHaveValue('Be concise and curious.');
 await expect(page.getByRole('switch',{name:'Notifications'})).toBeChecked();
 await expect(page.getByRole('button',{name:'Sage avatar'})).toHaveAttribute('aria-pressed','true');
 await page.getByLabel('Search bots').fill('story');await expect(page.locator('.bot-item')).toHaveCount(1);
 await page.getByLabel('Search bots').fill('');
 await page.getByRole('button',{name:'New conversation',exact:true}).click();await page.getByRole('button',{name:'Clear messages'}).click();
 await expect(page.locator('.message-bubble')).toHaveCount(0);
 await page.reload();await expect(page.locator('.message-bubble')).toHaveCount(0);
 await page.getByRole('button',{name:/Schedule Planner Make room/}).click();await expect(page.locator('.message-bubble')).toHaveText('Plan tomorrow');
 expect(errors).toEqual([]);
});
