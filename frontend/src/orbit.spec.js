test('1080p layout and blocked browser storage',async({page})=>{
 await page.setViewportSize({width:1920,height:1080});
 await page.addInitScript(()=>Object.defineProperty(window,'localStorage',{get(){throw new DOMException('Access denied','SecurityError');}}));
 await page.goto('http://127.0.0.1:5173');
 await expect(page.getByRole('alert')).toContainText('Browser storage is unavailable');
 await expect(page.locator('.bot-item')).toHaveCount(5);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByLabel('Message',{exact:true}).fill('Still works in this tab');await page.getByLabel('Message',{exact:true}).press('Enter');
 await expect(page.locator('.message-bubble')).toHaveText('Still works in this tab');
});
